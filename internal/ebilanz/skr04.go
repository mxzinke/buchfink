// Zuordnung der SKR04-Konten einer GmbH oder UG zu den Positionen der
// HGB-Taxonomie (Kerntaxonomie, Gesamtkostenverfahren).
//
// Die Regel nennt die Position für ein Konto oder einen Kontenbereich. Alt ist
// die Position, auf die das Konto wandert, wenn sein Saldo es in der Gliederung
// auf die Gegenseite stellt (Forderung mit Habensaldo, Bank im Soll), oder bei
// Konten mit wechselndem Saldo die Position der anderen Richtung
// (Bestandserhöhung/-minderung). Welche der beiden gilt, entscheidet die
// Gliederungsposition des Kontos (accounting.StatementKeyForAccount): die
// E-Bilanz weist ein Konto dort aus, wo es auch die Bilanz zeigt.
//
// Steht ein Konto unter einer Gliederungsposition, zu der die Regel nicht passt
// (eigenes Konto mit fremder Position), gilt die Auffangposition der
// Gliederungsposition (statementDefaults). Auffangpositionen „nicht zuordenbar"
// stehen nur dort, wo der SKR04 selbst nicht weiter unterscheidet
// (Leitfaden A.10.4).

