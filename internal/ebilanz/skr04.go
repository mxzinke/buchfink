// accountRule ist eine Regel mit ausgewertetem Kontenbereich.
type accountRule struct {
	from, to int
	ruleDef
}

type ruleTable []accountRule

func compileRules(defs []ruleDef) ruleTable {
	out := make(ruleTable, 0, len(defs))
	for _, d := range defs {
		from, to, err := parseRange(d.Accounts)
		if err != nil {
			panic(fmt.Sprintf("ebilanz: Regel %q: %v", d.Accounts, err))
		}
		out = append(out, accountRule{from: from, to: to, ruleDef: d})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].from < out[j].from })
	for i := 1; i < len(out); i++ {
		if out[i].from <= out[i-1].to {
			panic(fmt.Sprintf("ebilanz: Regeln %q und %q überschneiden sich", out[i-1].Accounts, out[i].Accounts))
		}
	}
	return out
}

func parseRange(s string) (int, int, error) {
	parts := strings.SplitN(s, "-", 2)
	from, err := strconv.Atoi(parts[0])
	if err != nil {
		return 0, 0, err
	}
	to := from
	if len(parts) == 2 {
		if to, err = strconv.Atoi(parts[1]); err != nil {
			return 0, 0, err
		}
	}
	if to < from {
		return 0, 0, fmt.Errorf("Bereich rückwärts")
	}
	return from, to, nil
}

// lookup findet die Regel eines Kontos.
func (t ruleTable) lookup(number string) (ruleDef, bool) {
	n, err := strconv.Atoi(number)
	if err != nil {
		return ruleDef{}, false
	}
	i := sort.Search(len(t), func(i int) bool { return t[i].to >= n })
	if i < len(t) && t[i].from <= n {
		return t[i].ruleDef, true
	}
	return ruleDef{}, false
}

